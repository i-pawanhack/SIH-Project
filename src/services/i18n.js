  res = res.replace(/\bHTTPS\b/gi, 'एचटीटीपीएस');
  res = res.replace(/\bJPEG\b/gi, 'जेपीईजी');
  res = res.replace(/\.JPG\b/gi, '.जेपीजी');
  res = res.replace(/\.JPEG\b/gi, '.जेपीईजी');
